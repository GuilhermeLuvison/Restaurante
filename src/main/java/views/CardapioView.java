    private void montarTabela() {
        ArrayList<Cardapio> itens = cac.listar();
        String[] colunas = {"Código", "Nome do Prato", "Ingredientes", "Categoria", "Tipo de Prato", "Preço", "Tempo de Preparo"};
        DefaultTableModel modelo = new DefaultTableModel(colunas, 0);

        for (int i = 0; i < itens.size(); i++) {
            Cardapio ca = itens.get(i);
            Object[] linha = {ca.getCodigo(), ca.getNome(), ca.getIngredientes(), ca.getCategoria(), ca.getTipoPrato(), ca.getPreco(), ca.getTempoPreparo()};
            modelo.addRow(linha);
        }

        tblCardapios.setModel(modelo);
    }

