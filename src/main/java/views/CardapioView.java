    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText();
        String ingredientes = txtIngredientes.getText();
        String categoria = txtCategoria.getText();
        String tipoPrato = txtTipoPrato.getText();
        double preco = Double.parseDouble(doublePreco.getText());
        String tempoPreparo = txtTempoPreparo.getText();

        Cardapio ca = new Cardapio(nome, ingredientes, categoria, tipoPrato, preco, tempoPreparo);
        montarTabela();

        if (codigo == 0) {
            cac.salvar(ca);
        } else {
            ca.setCodigo(codigo);
            cac.editar(ca);
            codigo = 0;
            btnCadastrar.setText("Cadastrar");
        }

        limparCampos();
        montarTabela();
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int codigoTabela = Integer.parseInt(String.valueOf(tblCardapios.getValueAt(tblCardapios.getSelectedRow(), 0)));
        Cardapio temp = cac.procurar(codigoTabela);

        txtNome.setText(temp.getNome());
        txtIngredientes.setText(temp.getIngredientes());
        txtCategoria.setText(temp.getCategoria());
        txtTipoPrato.setText(temp.getTipoPrato());
        doublePreco.setText(String.valueOf(temp.getPreco()));
        txtTempoPreparo.setText(temp.getTempoPreparo());

        btnCadastrar.setText("Atualizar Cadastro");
        codigo = codigoTabela;
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        Object linha = tblCardapios.getValueAt(tblCardapios.getSelectedRow(), 0);
        String codigoString = String.valueOf(linha);
        int codigoConvertido = Integer.parseInt(codigoString);
        cac.excluir(codigoConvertido);
        montarTabela();
    }//GEN-LAST:event_btnExcluirActionPerformed

